CREATE TABLE usuario (
    id_usuario       INT          GENERATED BY DEFAULT AS IDENTITY,
    tipo_usuario     VARCHAR(20)  NOT NULL,
    nome_usuario     VARCHAR(100) NOT NULL,
    email_usuario    VARCHAR(254) NOT NULL,
    senha_usuario    VARCHAR(255) NOT NULL,
    telefone_usuario VARCHAR(20),

    CONSTRAINT pk_usuario PRIMARY KEY (id_usuario),
    CONSTRAINT ck_usuario_tipo_usuario CHECK (tipo_usuario IN ('PACIENTE', 'FUNCIONARIO', 'MEDICO', 'ADMIN')),
    CONSTRAINT uq_usuario_email_usuario UNIQUE (email_usuario),
    CONSTRAINT uq_usuario_id_tipo UNIQUE (id_usuario, tipo_usuario)
);

CREATE TABLE admin (
    id_admin         INT         GENERATED BY DEFAULT AS IDENTITY,
    id_usuario       INT         NOT NULL,
    cpf_admin        VARCHAR(11) NOT NULL,
    tipo_usuario_ref VARCHAR(20) DEFAULT 'ADMIN' NOT NULL,

    CONSTRAINT pk_admin PRIMARY KEY (id_admin),
    CONSTRAINT fk_admin_usuario_tipo FOREIGN KEY (id_usuario, tipo_usuario_ref) REFERENCES usuario (id_usuario, tipo_usuario),
    CONSTRAINT uq_admin_id_usuario UNIQUE (id_usuario),
    CONSTRAINT uq_admin_cpf UNIQUE (cpf_admin),
    CONSTRAINT ck_admin_tipo_ref CHECK (tipo_usuario_ref = 'ADMIN')
);

CREATE TABLE paciente (
    id_paciente              INT         GENERATED BY DEFAULT AS IDENTITY,
    id_usuario               INT         NOT NULL,
    cpf_paciente             VARCHAR(11) NOT NULL,
    data_nascimento_paciente DATE        NOT NULL,
    tipo_usuario_ref         VARCHAR(20) DEFAULT 'PACIENTE' NOT NULL,

    CONSTRAINT pk_paciente PRIMARY KEY (id_paciente),
    CONSTRAINT uq_paciente_id_usuario UNIQUE (id_usuario),
    CONSTRAINT uq_paciente_cpf UNIQUE (cpf_paciente),
    CONSTRAINT ck_paciente_tipo_ref CHECK (tipo_usuario_ref = 'PACIENTE'),
    CONSTRAINT fk_paciente_usuario_tipo FOREIGN KEY (id_usuario, tipo_usuario_ref) REFERENCES usuario (id_usuario, tipo_usuario)
);

CREATE TABLE dependente (
    id_dependente              INT           GENERATED BY DEFAULT AS IDENTITY,
    id_paciente                INT           NOT NULL,
    cpf_dependente             VARCHAR(11)  NOT NULL,
    nome_dependente            VARCHAR(100) NOT NULL,
    data_nascimento_dependente DATE          NOT NULL,

    CONSTRAINT pk_dependente PRIMARY KEY (id_dependente),
    CONSTRAINT fk_dependente_paciente FOREIGN KEY (id_paciente) REFERENCES paciente (id_paciente),
    CONSTRAINT uq_dependente_cpf UNIQUE (cpf_dependente)
);

CREATE TABLE funcionario (
    id_funcionario      INT         GENERATED BY DEFAULT AS IDENTITY,
    id_usuario          INT         NOT NULL,
    cpf_funcionario     VARCHAR(11) NOT NULL,
    status_funcionario  VARCHAR(10) DEFAULT 'ATIVO' NOT NULL,
    tipo_usuario_ref    VARCHAR(20) DEFAULT 'FUNCIONARIO' NOT NULL,

    CONSTRAINT pk_funcionario PRIMARY KEY (id_funcionario),
    CONSTRAINT fk_funcionario_usuario_tipo FOREIGN KEY (id_usuario, tipo_usuario_ref) REFERENCES usuario (id_usuario, tipo_usuario),
    CONSTRAINT uq_funcionario_id_usuario UNIQUE (id_usuario),
    CONSTRAINT uq_funcionario_cpf_funcionario UNIQUE (cpf_funcionario),
    CONSTRAINT ck_funcionario_status_funcionario CHECK (status_funcionario IN ('ATIVO', 'INATIVO')),
    CONSTRAINT ck_funcionario_tipo_ref CHECK (tipo_usuario_ref = 'FUNCIONARIO')
);

CREATE TABLE medico (
    id_medico           INT          GENERATED BY DEFAULT AS IDENTITY,
    crm                 VARCHAR(20)  NOT NULL,
    id_usuario          INT          NOT NULL,
    especialidade_medico TEXT[] NOT NULL,
    sobre_medico        VARCHAR(500),
    valor_consulta      NUMERIC(10, 2),
    status_medico       VARCHAR(10)  DEFAULT 'ATIVO' NOT NULL,
    tipo_usuario_ref    VARCHAR(20)  DEFAULT 'MEDICO' NOT NULL,

    CONSTRAINT pk_medico PRIMARY KEY (id_medico),
    CONSTRAINT fk_medico_usuario_tipo FOREIGN KEY (id_usuario, tipo_usuario_ref) REFERENCES usuario (id_usuario, tipo_usuario),
    CONSTRAINT uq_medico_crm UNIQUE (crm),
    CONSTRAINT uq_medico_id_usuario UNIQUE (id_usuario),
    CONSTRAINT ck_medico_valor_consulta CHECK (valor_consulta >= 0),
    CONSTRAINT ck_medico_status_medico CHECK (status_medico IN ('ATIVO', 'INATIVO')),
    CONSTRAINT ck_medico_tipo_ref CHECK (tipo_usuario_ref = 'MEDICO')
);

CREATE TABLE horario_medico (
    id_horario         INT         GENERATED BY DEFAULT AS IDENTITY,
    id_medico          INT         NOT NULL,
    dia_semana         VARCHAR(10) NOT NULL,
    hora_inicio        TIME        NOT NULL,
    hora_fim           TIME        NOT NULL,
    intervalo_minutos  SMALLINT    DEFAULT 0 NOT NULL,

    CONSTRAINT pk_horario_medico           PRIMARY KEY (id_horario),
    CONSTRAINT fk_horario_medico_medico    FOREIGN KEY (id_medico) REFERENCES medico (id_medico),
    CONSTRAINT ck_horario_medico_dia       CHECK (dia_semana IN ('DOMINGO', 'SEGUNDA', 'TERCA', 'QUARTA', 'QUINTA', 'SEXTA', 'SABADO')),
    CONSTRAINT ck_horario_medico_intervalo CHECK (intervalo_minutos >= 0),
    CONSTRAINT ck_horario_medico_horas     CHECK (hora_inicio < hora_fim)
);

CREATE TABLE consulta (
    id_consulta     INT            GENERATED BY DEFAULT AS IDENTITY,
    id_paciente     INT            NOT NULL,
    id_dependente   INT            NULL,
    id_medico       INT            NOT NULL,
    data_consulta   TIMESTAMP      NOT NULL,
    valor_pago      NUMERIC(10, 2),
    status_consulta VARCHAR(20)    DEFAULT 'AGENDADA' NOT NULL,

    CONSTRAINT pk_consulta                 PRIMARY KEY (id_consulta),
    CONSTRAINT fk_consulta_paciente        FOREIGN KEY (id_paciente) REFERENCES paciente (id_paciente),
    CONSTRAINT fk_consulta_dependente      FOREIGN KEY (id_dependente) REFERENCES dependente (id_dependente),
    CONSTRAINT fk_consulta_medico          FOREIGN KEY (id_medico) REFERENCES medico (id_medico),
    CONSTRAINT ck_consulta_status_consulta CHECK (status_consulta IN ('AGENDADA', 'CONFIRMADA', 'CONCLUIDA', 'CANCELADA', 'NAO_COMPARECEU'))
);

-- Garante que um médico não tenha duas consultas no mesmo horário
CREATE UNIQUE INDEX uq_consulta_medico_ativa ON consulta (id_medico, data_consulta) WHERE status_consulta != 'CANCELADA';
