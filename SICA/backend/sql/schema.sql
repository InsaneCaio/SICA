-- Por as tabelas aqui
CREATE TABLE usuario (
    idUsuario       INT GENERATED BY DEFAULT AS IDENTITY,
    tipoUsuario     VARCHAR(20) NOT NULL,
    nomeUsuario     VARCHAR(100) NOT NULL,
    emailUsuario    VARCHAR(254) NOT NULL,
    senhaUsuario    VARCHAR(255) NOT NULL,
    telefoneUsuario VARCHAR(20),

    CONSTRAINT pk_usuario              PRIMARY KEY (idUsuario),
    CONSTRAINT ck_usuario_tipoUsuario  CHECK (tipoUsuario IN ('PACIENTE', 'FUNCIONARIO', 'MEDICO', 'ADMIN')),
    CONSTRAINT uq_usuario_emailUsuario UNIQUE (emailUsuario),
    CONSTRAINT uq_usuario_id_tipo      UNIQUE (idUsuario, tipoUsuario)
);


CREATE TABLE paciente (
    idPaciente              INT GENERATED BY DEFAULT AS IDENTITY,
    idUsuario               INT NOT NULL,
    CPF                     VARCHAR(11) NOT NULL,
    dataNascimentoPaciente  DATE,
    tipoUsuarioRef          VARCHAR(20) DEFAULT 'PACIENTE' NOT NULL,

    CONSTRAINT pk_paciente              PRIMARY KEY (idPaciente),
    CONSTRAINT uq_paciente_idUsuario    UNIQUE (idUsuario),
    CONSTRAINT uq_paciente_CPF          UNIQUE (CPF),
    CONSTRAINT ck_paciente_tipo_ref     CHECK (tipoUsuarioRef = 'PACIENTE'),
    CONSTRAINT fk_paciente_usuario_tipo FOREIGN KEY (idUsuario, tipoUsuarioRef) REFERENCES usuario (idUsuario, tipoUsuario)
);

CREATE TABLE funcionario (
    idFuncionario     INT GENERATED BY DEFAULT AS IDENTITY,
    idUsuario         INT NOT NULL,
    CPFFuncionario    VARCHAR(11) NOT NULL,
    statusFuncionario VARCHAR(10) DEFAULT 'ATIVO' NOT NULL,
    tipoUsuarioRef    VARCHAR(20) DEFAULT 'FUNCIONARIO' NOT NULL,

    CONSTRAINT pk_funcionario                   PRIMARY KEY (idFuncionario),
    CONSTRAINT fk_funcionario_usuario_tipo      FOREIGN KEY (idUsuario, tipoUsuarioRef) REFERENCES usuario (idUsuario, tipoUsuario),
    CONSTRAINT uq_funcionario_idUsuario         UNIQUE (idUsuario),
    CONSTRAINT uq_funcionario_CPFFuncionario    UNIQUE (CPFFuncionario),
    CONSTRAINT ck_funcionario_statusFuncionario CHECK (statusFuncionario IN ('ATIVO', 'INATIVO')),
    CONSTRAINT ck_funcionario_tipo_ref          CHECK (tipoUsuarioRef = 'FUNCIONARIO')

);


CREATE TABLE medico (
    idMedico            INT GENERATED BY DEFAULT AS IDENTITY,
    CRM                 VARCHAR(20) NOT NULL,
    idUsuario           INT NOT NULL,
    especialidadeMedico VARCHAR(100) NOT NULL,
    sobreMedico         VARCHAR(500),
    valorConsulta       NUMERIC(10, 2),
    statusMedico        VARCHAR(10) DEFAULT 'ATIVO' NOT NULL,
    tipoUsuarioRef      VARCHAR(20) DEFAULT 'MEDICO' NOT NULL,

    CONSTRAINT pk_medico PRIMARY KEY (idMedico),
    CONSTRAINT fk_medico_usuario_tipo
        FOREIGN KEY (idUsuario, tipoUsuarioRef)
        REFERENCES usuario (idUsuario, tipoUsuario),
    CONSTRAINT uq_medico_CRM UNIQUE (CRM),
    CONSTRAINT uq_medico_idUsuario UNIQUE (idUsuario),
    CONSTRAINT ck_medico_valorConsulta
        CHECK (valorConsulta >= 0),
    CONSTRAINT ck_medico_statusMedico
        CHECK (statusMedico IN ('ATIVO', 'INATIVO')),
    CONSTRAINT ck_medico_tipo_ref
        CHECK (tipoUsuarioRef = 'MEDICO')
);


CREATE TABLE horario_medico (
    idHorario        INT GENERATED BY DEFAULT AS IDENTITY,
    idMedico         INT NOT NULL,
    diaSemana        VARCHAR(10) NOT NULL,
    horaInicio       TIME NOT NULL,
    horaFim          TIME NOT NULL,
    intervaloMinutos SMALLINT DEFAULT 0 NOT NULL,

    CONSTRAINT pk_horario_medico PRIMARY KEY (idHorario),
    CONSTRAINT fk_horario_medico_medico
        FOREIGN KEY (idMedico) REFERENCES medico (idMedico),
    CONSTRAINT ck_horario_medico_dia
        CHECK (diaSemana IN (
            'DOMINGO', 'SEGUNDA', 'TERCA', 'QUARTA',
            'QUINTA', 'SEXTA', 'SABADO'
        )),
    CONSTRAINT ck_horario_medico_intervalo
        CHECK (intervaloMinutos >= 0),
    CONSTRAINT ck_horario_medico_horas
        CHECK (horaInicio < horaFim)
);